/**
 * Daily question packs. Everyday is free; the others need Closer Plus.
 * `adult` packs also need both members to have confirmed they are 18+.
 * Question ids are stable: never reuse or renumber an id.
 */
export interface QuestionPack {
  id: string;
  title: string;
  premium: boolean;
  adult: boolean;
  /** Which pair modes the pack suits ("any" = both). */
  modes: Array<"couple" | "friends">;
  questions: Array<{id: string; text: string}>;
}

const q = (prefix: string, texts: string[]) =>
  texts.map((text, i) => ({id: `${prefix}_${String(i + 1).padStart(3, "0")}`, text}));

